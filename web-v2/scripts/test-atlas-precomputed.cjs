const assert=require('node:assert/strict');
const path=require('node:path');
const load=require('./load-project-ts.cjs');
const {packLayer,unpackLayer,selectYears,mergeAtlasRows,estimateRemaining,atlasSignature}=load(path.join(__dirname,'../lib/atlas-precomputed.ts'));
const {summarizeCell}=load(path.join(__dirname,'../lib/atlas.ts'));
const metadata={crop:'maize',season:'maize__rf',rule_id:'test',signature:'fixture',first:2000,last:2004,generated_at:'2026-09-28T00:00:00Z'};
const row={cell:'1.25,2.25',phase:'EST',years:[{year:2000,event:true},{year:2001,event:false},{year:2002,event:null},{year:2003,event:null,error:'failed'}]};
const key='1.25,2.25|EST';
const layer=packLayer({[key]:row},metadata);
assert.equal(layer.cells[0][2],'10uf.');
const decoded=unpackLayer(layer,metadata);
assert.equal(decoded[key].years.length,4);
assert.equal(summarizeCell(decoded[key],5).probability,.5);
assert.equal(summarizeCell(decoded[key],5).partial,true);
assert.equal(summarizeCell(selectYears(decoded,2001,2002)[key],2).probability,0);
assert.equal(selectYears(decoded,2010,2012)[key].years.length,0);
assert.throws(()=>unpackLayer(layer,{...metadata,signature:'changed threshold'}),/does not match/);
assert.throws(()=>unpackLayer({...layer,cells:[[row.cell,row.phase,'10x00']]},metadata),/Invalid annual/);
assert.throws(()=>unpackLayer({...layer,cells:[...layer.cells,...layer.cells]},metadata),/Duplicate/);
const failed={...row,years:[{year:2000,event:null,error:'timeout'}]};
assert.equal(mergeAtlasRows(decoded,{[key]:failed})[key].years[0].event,true);
const repaired={...row,years:[{year:2003,event:false}]};
assert.equal(mergeAtlasRows(decoded,{[key]:repaired})[key].years.find(y=>y.year===2003).error,undefined);
assert.equal(estimateRemaining(20,4,12),40);
assert.equal(estimateRemaining(20,3,12),null);
assert.equal(estimateRemaining(20,12,12),0);
assert.equal(atlasSignature({b:2,a:1},'v1'),atlasSignature({a:1,b:2},'v1'));
assert.notEqual(atlasSignature({a:1},'v1'),atlasSignature({a:1},'v2'));
console.log('Precomputed atlas: state encoding, year filtering, cache compatibility, failure repair and ETA passed.');
